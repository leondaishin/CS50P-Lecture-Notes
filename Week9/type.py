# printing the type of the thing "50" which is int 
# terminal will say <class 'int'>
# also a class type 
print(type(50))

# this is a string (also a class type) 
print(type("Hello World"))

# this is a list (also a class type)
# those are identical completely
print(type([]))
print(type(list()))

# Dict is a class as well
# both are completely the same
print(type({}))
print(type(dict()))
