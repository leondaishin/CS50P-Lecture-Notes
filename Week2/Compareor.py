# Asking x and y for the numbers: 
x = float(input("What is x? "))
y = float(input("What is y? "))

# comparing x and y with an or at the end of the line: 
if x < y or x > y: 
    print("x is not equal to y")
else: 
    print("x is equal to y")

# asking if x != y then its easier for code: 
if x != y: 
    print("x is not equal to y")
else: 
    print("x is equal to y")

# These are 2 versions of code that is identical

