# Defining score variable:

score = int(input("What is your score?: "))

#if and using and to check where the person is: 

if score >= 90 <= 100: 
    print("You got an A!")
elif score >= 80 < 90:
    print("You did well. You got a B!")
elif score >= 70 < 80: 
    print("You got a C. ")
elif score >= 60 < 70: 
    print("You did half as good. You got a D. ")
else: 
    print("You failed. You got an F. ")


